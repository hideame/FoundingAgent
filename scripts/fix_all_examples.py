ALL_INDUSTRIES = {
    "restaurant": RESTAURANT_SECTIONS,
    "beauty": BEAUTY_SECTIONS,
    "apparel": APPAREL_SECTIONS,
    "construction": CONSTRUCTION_SECTIONS,
    "cram_school": CRAM_SCHOOL_SECTIONS,
    "care_service": CARE_SERVICE_SECTIONS,
    "car_sales": CAR_SALES_SECTIONS,
    "dentist": DENTIST_SECTIONS,
    "software": SOFTWARE_SECTIONS,
}


async def update_all_examples():
    """全業種のexample_contentsを更新"""
    async with AsyncSessionLocal() as session:
        for industry_type, sections in ALL_INDUSTRIES.items():
            # 既存データを削除
            print(f"\n--- {industry_type} ---")
            await session.execute(
                delete(ExampleContent).where(
                    ExampleContent.industry_type == industry_type
                )
            )
            await session.commit()

            # 新しいデータを挿入
            count = 0
            for section_key, example_text in sections.items():
                example = ExampleContent(
                    industry_type=industry_type,
                    section_key=section_key,
                    example_text=example_text,
                )
                session.add(example)
                count += 1

            await session.commit()
            print(f"  {count} セクション挿入完了")

        # 全体の検証
        print("\n=== 全体検証 ===")
        result = await session.execute(select(ExampleContent))
        rows = result.scalars().all()

        by_industry = {}
        for row in rows:
            if row.industry_type not in by_industry:
                by_industry[row.industry_type] = []
            by_industry[row.industry_type].append(row.section_key)

        total = 0
        for industry_type in sorted(by_industry.keys()):
            section_keys = by_industry[industry_type]
            total += len(section_keys)
            print(f"  {industry_type}: {len(section_keys)} セクション ({', '.join(sorted(section_keys))})")

        print(f"\n合計: {total} レコード")


if __name__ == "__main__":
    asyncio.run(update_all_examples())
